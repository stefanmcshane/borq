export function generateWordName(maxLength = 10): string {
  if (!Number.isInteger(maxLength)) {
    throw new RangeError("Name length must be an integer.");
  }
  const choices = nameAdjectives.flatMap((word) => {
    const nouns = nameNouns.filter(
      (noun) => word.length + noun.length + 1 <= maxLength,
    );
    return nouns.length ? [{ word, nouns }] : [];
  });
  const choice = choices[Math.floor(Math.random() * choices.length)];
  if (!choice) {
    throw new RangeError("Name length must fit two whole words and a hyphen.");
  }
  return (
    choice.word +
    "-" +
    choice.nouns[Math.floor(Math.random() * choice.nouns.length)]
  );
}
